static const sgl_icon_pixmap_t icon_volume = {
    .width = 16,
    .height = 16,
    .bitmap = icon_volume_bitmap,
};

/**
 * @brief create icon drawing examples
 * @param parent parent object, NULL creates the icons on the active screen
 * @return none
 */
void sgl_icon_test_examples(sgl_obj_t *parent)
{
    sgl_obj_t *icon;

    icon = sgl_icon_create(parent);
    sgl_icon_set_icon(icon, &icon_volume);
    sgl_icon_set_alpha(icon, SGL_ALPHA_MAX);
    sgl_obj_set_pos(icon, 100, 100);
    sgl_obj_set_size(icon, 16, 16);

    icon = sgl_icon_create(parent);
    sgl_icon_set_icon(icon, &icon_volume);
    sgl_icon_set_alpha(icon, 128);
    sgl_obj_set_pos(icon, 130, 100);
    sgl_obj_set_size(icon, 16, 16);

    icon = sgl_icon_create(parent);
    sgl_icon_set_icon(icon, &icon_volume);
    sgl_icon_set_alpha(icon, 64);
    sgl_obj_set_pos(icon, 160, 100);
    sgl_obj_set_size(icon, 16, 16);
}
